/*
 * OV5693 Register Map Reference
 * ==============================
 *
 * Each mode table programs the sensor from scratch. Register groups:
 *
 * --- System & I/O Control (0x3000-0x3031) ---
 * 0x0100       mode_select: 0x00=standby, 0x01=streaming
 * 0x0103       software_reset: write 0x01 to reset
 * 0x3001       pad_output_enable: I/O direction control
 * 0x3002       pad_output_value: I/O output value
 * 0x3006       pad_output_select: VSYNC/HREF/PCLK routing
 * 0x3011       mipi_lane_mode: bit[5]=0:1-lane, 1:2-lane (OV5693 max is 2 lanes)
 * 0x3012-0x3018 pad_control: drive strength, pull-up/down
 * 0x301b       chip_revision
 * 0x301d       pad_output_select2
 * 0x3021       misc_ctrl: bit stream control
 * 0x3022       mipi_pad_enable
 * 0x3028       pad_output_select6
 *
 * --- PLL Configuration (0x3098-0x30b6) ---
 * 0x3098       pll_pre_div_sp: system PLL pre-divider
 * 0x3099       pll_mul_sp: system PLL multiplier
 * 0x309a       pll_pre_div_s: system PLL secondary pre-divider
 * 0x309b       pll_div_s: system PLL secondary divider
 * 0x309c       pll_sel: PLL selection bits
 * 0x30a0       pll_ctrl_a: PLL control register A
 * 0x30a2       pll_ctrl_b: PLL control register B
 * 0x30b2       pll_pre_div_mipi: MIPI PLL pre-divider
 * 0x30b3       pll_mul_mipi: MIPI PLL multiplier (pixel clock)
 * 0x30b4       pll_div_mipi: MIPI PLL divider
 * 0x30b5       pll_pre_div2_mipi: MIPI PLL secondary pre-divider
 * 0x30b6       pll_div2_mipi: MIPI PLL secondary divider
 * 0x3104       sccb_pll: SCCB/PLL control
 * 0x3106       sccb_ctrl: system root divider
 *
 * --- AEC/AGC (0x3500-0x350b) ---
 * 0x3500-0x3502 aec_expo: exposure [19:16],[15:8],[7:0]
 * 0x3503       aec_manual: bit[0]=AGC manual, bit[1]=AEC manual
 * 0x3504-0x3506 aec_long_expo: long exposure (HDR)
 * 0x3507-0x3509 aec_short_expo: short exposure (HDR)
 * 0x350a-0x350b aec_gain: analog gain [9:8],[7:0]
 *
 * --- Analog Control (0x3600-0x3680) ---
 * 0x3601-0x3634 analog_ctrl: analog circuit tuning
 * 0x364d-0x366a analog_ctrl2: more analog tuning
 * 0x3680-0x3681 analog_ctrl3: final analog settings
 *
 * --- Sensor Timing (0x3700-0x37df) ---
 * 0x3700-0x379c sensor_timing: pixel readout timing
 * 0x37c5-0x37df sensor_timing2: additional timing control
 *   These registers control charge transfer, reset timing,
 *   and row/column readout sequencing. Values are mode-specific
 *   and typically come from OmniVision characterization data.
 *
 * --- Windowing & Frame Size (0x3800-0x382a) ---
 * 0x3800-0x3801 x_start: H crop start [11:8],[7:0]
 * 0x3802-0x3803 y_start: V crop start [11:8],[7:0]
 * 0x3804-0x3805 x_end: H crop end [11:8],[7:0]
 * 0x3806-0x3807 y_end: V crop end [11:8],[7:0]
 * 0x3808-0x3809 x_output: H output size [11:8],[7:0]
 * 0x380a-0x380b y_output: V output size [11:8],[7:0]
 * 0x380c-0x380d HTS: horizontal total size (line length in pclk)
 *               Controls horizontal blanking. fps = pclk / (HTS * VTS)
 * 0x380e-0x380f VTS: vertical total size (frame length in lines)
 *               Controls vertical blanking. Increase = lower fps.
 * 0x3810-0x3811 x_offset: H windowing offset
 * 0x3812-0x3813 y_offset: V windowing offset
 * 0x3814       h_subsample_inc: H subsample odd/even increment
 *              0x11=no skip, 0x31=2x binning
 * 0x3815       v_subsample_inc: V subsample odd/even increment
 * 0x3820       format_ctrl: vflip, binning mode
 * 0x3821       format_ctrl2: hflip, binning mode
 * 0x382a       auto_vts_inc: auto VTS step size
 *
 * --- AEC Control (0x3a00-0x3a13) ---
 * 0x3a04-0x3a05 aec_max_expo60: max exposure for 60Hz
 * 0x3a06-0x3a07 aec_max_expo50: max exposure for 50Hz
 *
 * --- BLC (0x4000-0x4058) ---
 * 0x4000       blc_ctrl00: BLC enable/mode
 * 0x4001       blc_ctrl01: BLC target
 * 0x4002       blc_ctrl02: BLC dark frame control
 * 0x4004       blc_ctrl04: number of black lines
 * 0x4005       blc_ctrl05: BLC always update
 *
 * --- MIPI Control (0x4800-0x4837) ---
 * 0x4800       mipi_ctrl00: bit[5]=gate clk, bit[0]=lp11 when idle
 *              0x20=dis-continuous clock, 0x24=continuous clock
 * 0x4806       mipi_ctrl06: virtual channel
 * 0x4816       mipi_data_format: data type
 * 0x481f       mipi_clk_period
 * 0x4826       mipi_hs_prepare: HS prepare time
 * 0x4831       mipi_hs_trail: HS trail time
 * 0x4837       mipi_pclk_div: MIPI pixel clock divider
 *
 * --- ISP Control (0x5000-0x5046) ---
 * 0x5000       isp_ctrl00: DPC enable, lens correction
 * 0x5001       isp_ctrl01: BLC enable
 * 0x5002       isp_ctrl02: OTP, AWB gain control
 * 0x5046       isp_ctrl46: threshold settings
 *
 * --- DPC (0x5780-0x5791) ---
 * 0x5780-0x5791 dpc_ctrl: defect pixel correction thresholds
 *
 * --- LENC (0x5842-0x5849) ---
 * 0x5842-0x5849 lenc: lens shading correction coefficients
 *
 * --- Test Pattern (0x5e00-0x5e10) ---
 * 0x5e00       test_pattern: 0x80=color bar, 0x00=disabled
 * 0x5e10       test_pattern_ctrl
 *
 * --- Mocha-specific Notes ---
 * The Mi Pad OV5693 is connected via CSI-E with 1 MIPI data lane.
 * Reference boards use 2 lanes on CSI-A. Each mode table ends
 * with "Mocha 1-lane CSI-E overrides" that adjust:
 *   0x3011 = 0x11 (1-lane mode, reference uses 0x21 for 2-lane)
 *   0x3015 = 0x28 (PLL divider for reduced lane bandwidth)
 *   0x380c/d = increased HTS to reduce data rate on fewer lanes
 *
 * Frame rate formula:
 *   fps = pixel_clock / (HTS * VTS)
 *   pixel_clock is derived from XVCLK (24MHz) through the PLL chain.
 */

